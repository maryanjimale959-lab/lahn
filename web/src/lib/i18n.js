const STORAGE = 'lahn.lang';

export function loadLang() {
  const saved = localStorage.getItem(STORAGE);
  if (saved === 'en' || saved === 'so') return saved;
  return (navigator.language || 'en').toLowerCase().startsWith('so') ? 'so' : 'en';
}

export function saveLang(lang) {
  localStorage.setItem(STORAGE, lang);
  document.documentElement.lang = lang;
}

/* Somali and English both read left to right; this stays for the day a third language lands. */
export function applyDir(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = 'ltr';
}

export function translate(lang, key, vars) {
  let out = dict[lang]?.[key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

