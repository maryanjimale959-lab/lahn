const RULES = { en: new Intl.PluralRules('en'), so: new Intl.PluralRules('so') };

/** "3 songs" / "3 heesood" — count and noun together, with the right plural form. */
export function plural(lang, n, key) {
  const forms = NOUNS[lang]?.[key] ?? NOUNS.en[key];
  const one = (RULES[lang] ?? RULES.en).select(n) === 'one';
  return `${n} ${forms[one ? 0 : 1]}`;
}
