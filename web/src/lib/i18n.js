const STORAGE = 'lahn.lang';

export function loadLang() {
  const saved = localStorage.getItem(STORAGE);
  if (saved === 'en' || saved === 'ar') return saved;
  return (navigator.language || 'en').toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function saveLang(lang) {
  localStorage.setItem(STORAGE, lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

export function applyDir(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

export function translate(lang, key, vars) {
  let out = dict[lang]?.[key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

export const arabicDigits = (n) => String(n).replace(/\d/g, (d) => '٠١٢٣٤٥٦٧٨٩'[d]);

/* Arabic has six grammatical numbers, English two. */
const NOUNS = {
  en: {
    song: ['song', 'songs'],
    artist: ['artist', 'artists'],
    album: ['album', 'albums'],
    playlist: ['playlist', 'playlists'],
    play: ['play', 'plays'],
  },
  ar: {
    /* [one, two, few, many, other] */
    song: ['أغنية', 'أغنيتان', 'أغاني', 'أغنية', 'أغنية'],
    artist: ['فنان', 'فنانان', 'فنانين', 'فنانًا', 'فنان'],
    album: ['ألبوم', 'ألبومان', 'ألبومات', 'ألبومًا', 'ألبوم'],
    playlist: ['قائمة', 'قائمتان', 'قوائم', 'قائمة', 'قائمة'],
    play: ['تشغيل', 'تشغيلان', 'تشغيلات', 'تشغيلًا', 'تشغيل'],
  },
};

const EN_PLURAL = new Intl.PluralRules('en');
const AR_PLURAL = new Intl.PluralRules('ar');
const AR_INDEX = { zero: 4, one: 0, two: 1, few: 2, many: 3, other: 4 };

/** "3 songs" / "٣ أغاني" — count and noun together, with the right plural form. */
export function plural(lang, n, key) {
  const forms = NOUNS[lang]?.[key] ?? NOUNS.en[key];
  const word =
    lang === 'ar'
      ? forms[AR_INDEX[AR_PLURAL.select(n)]] ?? forms[4]
      : forms[EN_PLURAL.select(n) === 'one' ? 0 : 1];
  return `${lang === 'ar' ? arabicDigits(n) : n} ${word}`;
}
